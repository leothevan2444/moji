#!/usr/bin/env python3
"""Generate immutable .NET SBCS mappings for every legacy label in v11 corpus.

Only pinned data is read. No downloaded C# code is compiled or executed.
Network access requires --download; --source-dir supports offline regeneration.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import urllib.request


ROOT = Path(__file__).resolve().parents[2]
LOCK = Path(__file__).with_name("sources.lock.json")
OUTPUT = ROOT / "internal/cardigann/sbcs_encoding.gen.go"
LICENSE = ROOT / "internal/cardigann/DOTNET-LICENSE.txt"
MAX_SOURCE = 2 << 20


def tables(data, pages, latin_source):
    u16 = lambda p: struct.unpack_from("<H", data, p)[0]
    indices = {
        u16(44 + 40 * i + 32): struct.unpack_from("<I", data, 44 + 40 * i + 36)[0]
        for i in range(u16(40)) if u16(44 + 40 * i + 34) == 1
    }
    result = {}
    for page in pages:
        if page == 28591:
            continue
        start = indices[page] + 48
        raw = [u16(start + i * 2) for i in range(256)]
        # A zero value at a nonzero byte is an unmapped slot, not another NUL.
        raw = [0xfffd if rune == 0 and byte else rune for byte, rune in enumerate(raw)]
        encoder = {rune: byte for byte, rune in enumerate(raw) if rune != 0xfffd}
        decoder = raw.copy()
        position = start + 512
        while u16(position):
            byte, rune = u16(position), u16(position + 2)
            position += 4
            if byte >= 256 or raw[byte] != 0xfffd:
                raise ValueError("invalid decoder best-fit record")
            decoder[byte] = rune
        position += 2
        codepoint = u16(position)
        position += 2
        while codepoint < 0x10000:
            value = data[position]
            position += 1
            if value == 1:
                next_codepoint = u16(position)
                position += 2
                if next_codepoint <= codepoint:
                    raise ValueError("non-increasing encoder best-fit position")
                codepoint = next_codepoint
            elif 0 < value < 0x20 and value != 0x1e:
                codepoint += value
            else:
                if value == 0x1e:
                    value = data[position]
                    position += 1
                if value and codepoint not in encoder:
                    if raw[value] == 0xfffd:
                        raise ValueError("best-fit target is not a round-trip character")
                    encoder[codepoint] = encoder[raw[value]]
                codepoint += 1
        decoder = [ord("?") if rune == 0xfffd else rune for rune in decoder]
        result[page] = (encoder, decoder)

    if 28591 in pages:
        source = re.sub(r"//[^\n]*", "", latin_source)
        values = [int(v, 16) for v in re.findall(r"\(char\)0x([0-9a-fA-F]+)", source)]
        if not values or len(values) % 2:
            raise ValueError("invalid Latin-1 best-fit pairs")
        encoder = {r: r for r in range(256)}
        for rune, value in zip(values[::2], values[1::2]):
            if value > 255:
                raise ValueError("Latin-1 best-fit target exceeds one byte")
            encoder.setdefault(rune, value)
        result[28591] = (encoder, list(range(256)))
    for encoder, decoder in result.values():
        if encoder.get(ord("?")) != ord("?") or len(decoder) != 256:
            raise ValueError("unsupported replacement or decoder layout")
    return result


def go_bytes(data):
    return " +\n".join('"' + "".join(f"\\x{b:02x}" for b in data[i:i+48]) + '"'
                         for i in range(0, len(data), 48))


def generate(sources, lock):
    pages = tables(sources["codepages.nlp"], lock["codePages"],
                   sources["EncoderLatin1BestFitFallback.Data.cs"].decode("utf-8"))
    lines = ["// Code generated by scripts/cardigann-encodings/generate.py; DO NOT EDIT.",
             "// Derived from .NET runtime v9.0.0 data under MIT; see DOTNET-LICENSE.txt.",
             "package cardigann\n", "var dotNetSingleByteCodePages = map[uint16]*singleByteEncoding{"]
    for page, (encoder, decoder) in sorted(pages.items()):
        encoded = b"".join(struct.pack("<HB", rune, byte) for rune, byte in sorted(encoder.items()))
        decoded = b"".join(struct.pack("<H", rune) for rune in decoder)
        lines.extend([f"{page}: {{", "decode: " + go_bytes(decoded) + ",",
                      "encode: " + go_bytes(encoded) + ",", "},"])
    lines.append("}\nvar dotNetSingleByteAliases = map[string]uint16{")
    # Latin-1 belongs to CoreLib, so the CodePages provider CSV omits it.
    aliases = {"iso-8859-1": 28591} if 28591 in pages else {}
    for line in sources["CodePageNameMappings.csv"].decode("utf-8-sig").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, page = line.split(";")
        if int(page) in pages:
            aliases[name.lower()] = int(page)
    if set(aliases.values()) != set(pages):
        raise ValueError("a code page has no aliases")
    for name, page in sorted(aliases.items()):
        lines.append(f"{json.dumps(name)}: {page},")
    lines.append("}\n")
    return subprocess.run(["gofmt"], input="\n".join(lines).encode(),
                          stdout=subprocess.PIPE, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--source-dir", type=Path)
    source.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lock = json.loads(LOCK.read_text())
    sources = {}
    for entry in lock["sources"]:
        if args.source_dir:
            data = (args.source_dir / entry["file"]).read_bytes()
        else:
            url = f"https://raw.githubusercontent.com/{lock['repository']}/{lock['ref']}/{entry['path']}"
            request = urllib.request.Request(url, headers={"User-Agent": "Moji-Encoding-Data-Generator"})
            with urllib.request.urlopen(request, timeout=60) as response:
                data = response.read(MAX_SOURCE + 1)
        if len(data) > MAX_SOURCE or hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise ValueError(f"pinned source checksum mismatch: {entry['file']}")
        sources[entry["file"]] = data
    outputs = {OUTPUT: generate(sources, lock), LICENSE: sources["LICENSE.TXT"]}
    for path, data in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise ValueError(f"generated file differs: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(data)
    print(f".NET encoding data: {len(lock['codePages'])} code pages verified")


if __name__ == "__main__":
    main()
